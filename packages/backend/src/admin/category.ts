/** Первое слово названия — вид изделия («Джемпер», «Туфли»); пусто, если названия нет. */
export function kindOf(name: string): string {
  const word = name.trim().split(/[\s,]+/)[0] ?? '';
  const clean = word.replace(/[^\p{L}-]/gu, '');
  if (!clean) return '';
  return clean[0]!.toUpperCase() + clean.slice(1).toLowerCase();
}

export function categoryOf(name: string): Category {
  const first = normalizeText(kindOf(name));
  if (first) {
    for (const cat of ['Обувь', 'Сумки', 'Аксессуары'] as const) {
      if (STEMS[cat].some((s) => first.startsWith(s))) return cat;
    }
  }
  return 'Одежда';
}
